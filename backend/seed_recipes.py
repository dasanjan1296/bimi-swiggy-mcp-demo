# ── Helper to build ingredient dicts ──

def ing(name: str, qty, unit: str, category: str = "other",
        *, hindi: str = None, optional: bool = False,
        prep: str = None, subs: list[str] = None,
        match_key: str = None) -> dict:
    d = {
        "name": name,
        "quantity": qty,
        "unit": unit,
        "category": category,
        "is_optional": optional,
        "inventory_match_key": match_key or name.lower(),
    }
    if hindi:
        d["name_hindi"] = hindi
    if prep:
        d["prep_note"] = prep
    if subs:
        d["substitutes"] = subs
    return d


