async def seed():
    async with engine.begin() as conn:
        await conn.run_sync(Base.metadata.create_all)

    async with async_session() as db:
        count = 0
        for data in RECIPES:
            recipe = Recipe(
                name=data["name"],
                name_hindi=data.get("name_hindi"),
                slug=_slugify(data["name"]),
                description=data.get("description"),
                cuisine=data["cuisine"],
                course=data["course"],
                diet_type=data["diet_type"],
                prep_time_mins=data["prep_time_mins"],
                cook_time_mins=data["cook_time_mins"],
                total_time_mins=data["total_time_mins"],
                default_servings=data.get("default_servings", 4),
                ingredients=data["ingredients"],
                instructions=data.get("instructions"),
                nutrition_per_serving=data.get("nutrition_per_serving"),
                health_tags=data.get("health_tags"),
                difficulty=data.get("difficulty", "medium"),
                tags=data.get("tags"),
                source_url=data.get("source_url"),
                source_name=data.get("source_name"),
                youtube_search_query=data.get("youtube_search_query"),
                image_url=data.get("image_url"),
                advance_prep_note=data.get("advance_prep_note"),
                pairs_well_with=data.get("pairs_well_with"),
            )
            recipe.sync_derived_fields()
            db.add(recipe)
            count += 1

        await db.commit()
        print(f"Seeded {count} recipes into the archive.")
